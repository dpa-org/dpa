#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bidirectional_roundtrip() {
        for (zh, en) in [
            ("A1Z26 密码解密", "A1Z26 Cipher Decode"),
            ("AES 加密", "AES Encrypt"),
            ("转为 Hex", "To Hex"),
        ] {
            assert_eq!(zh_to_en(zh), Some(en));
            assert_eq!(en_to_zh(en), Some(zh));
        }
    }

    #[test]
    fn unknown_names_pass_through() {
        assert_eq!(zh_to_en("不存在 的操作"), None);
        assert_eq!(en_to_zh("No Such Op"), None);
    }

    #[test]
    fn identity_names() {
        assert_eq!(zh_to_en("ADD"), Some("ADD"));
        assert_eq!(en_to_zh("ADD"), Some("ADD"));
    }
}
