/// Chinese operation name -> English operation name
pub(crate) fn zh_to_en(name: &str) -> Option<&'static str> {
    ZH_TO_EN
        .iter()
        .find(|pair| pair.0 == name)
        .map(|pair| pair.1)
}

/// English operation name -> Chinese operation name
pub(crate) fn en_to_zh(name: &str) -> Option<&'static str> {
    EN_TO_ZH
        .iter()
        .find(|pair| pair.0 == name)
        .map(|pair| pair.1)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The previous hand-written test sampled only 3 entries;
    /// now every row of both tables is asserted bidirectionally and the key
    /// sets are checked for symmetry.
    #[test]
    fn full_map_consistency() {
        assert_eq!(ZH_TO_EN.len(), EN_TO_ZH.len());
        for pair in ZH_TO_EN {
            let zh = pair.0;
            let en = pair.1;
            assert_eq!(zh_to_en(zh), Some(en), "zh_to_en miss: {}", zh);
            assert_eq!(en_to_zh(en), Some(zh), "en_to_zh miss: {}", en);
        }
        // Key set symmetry: every Chinese key resolves to an English key that
        // maps back to the original Chinese key, and vice versa.
        for pair in ZH_TO_EN {
            let en = zh_to_en(pair.0).unwrap();
            assert_eq!(en_to_zh(en), Some(pair.0));
        }
        for pair in EN_TO_ZH {
            let zh = en_to_zh(pair.0).unwrap();
            assert_eq!(zh_to_en(zh), Some(pair.0));
        }
    }

    #[test]
    fn unknown_names_pass_through() {
        assert_eq!(zh_to_en("No such operation"), None);
        assert_eq!(en_to_zh("No Such Op"), None);
    }

    #[test]
    fn identity_names() {
        assert_eq!(zh_to_en("ADD"), Some("ADD"));
        assert_eq!(en_to_zh("ADD"), Some("ADD"));
    }
}
